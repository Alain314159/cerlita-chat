def bullets(story, items):
    for it in items:
        story.append(Paragraph(f"• {it}", S["bullet"]))
    story.append(Spacer(1, 4))


def table(story, header, rows, ratios, caption=None, bold_first_col=False):
    """Tabla estándar: celdas Paragraph, anchos proporcionales, centrada."""
    widths = [r * AVAIL_W * 0.98 for r in ratios]
    data = [[Paragraph(f"<b>{c}</b>", S["th"]) for c in header]]
    for row in rows:
        cells = []
        for j, c in enumerate(row):
            st = S["tdb"] if (bold_first_col and j == 0) else S["td"]
            cells.append(Paragraph(str(c), st))
        data.append(cells)
    t = Table(data, colWidths=widths, hAlign="CENTER", repeatRows=1)
    style = [
        ("BACKGROUND", (0, 0), (-1, 0), TABLE_HEADER_COLOR),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("GRID", (0, 0), (-1, -1), 0.5, BORDER),
        ("LEFTPADDING", (0, 0), (-1, -1), 7),
        ("RIGHTPADDING", (0, 0), (-1, -1), 7),
        ("TOPPADDING", (0, 0), (-1, -1), 5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
    ]
    for i in range(1, len(data)):
        style.append(("BACKGROUND", (0, i), (-1, i),
                      TABLE_ROW_EVEN if i % 2 == 1 else TABLE_ROW_ODD))
    t.setStyle(TableStyle(style))
    story.append(Spacer(1, 12))
    if caption:
        if len(rows) <= 15:
            story.append(KeepTogether([t, Spacer(1, 4), Paragraph(caption, S["caption"])]))
        else:
            story.append(t)
            story.append(Spacer(1, 4))
            story.append(Paragraph(caption, S["caption"]))
    else:
        story.append(t)
    story.append(Spacer(1, 10))


def stats(story, items):
    """Fila de 2-4 callouts de datos: [(valor, etiqueta), ...]"""
    n = len(items)
    gap = 10
    w = (AVAIL_W * 0.96 - gap * (n - 1)) / n
    cells = []
    for val, lbl in items:
        inner = Table(
            [[Paragraph(f"<b>{val}</b>", S["stat"])], [Paragraph(lbl, S["statlbl"])]],
            colWidths=[w - 2],
        )
        inner.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, -1), CARD_BG),
            ("BOX", (0, 0), (-1, -1), 1, ACCENT),
            ("TOPPADDING", (0, 0), (-1, 0), 9),
            ("BOTTOMPADDING", (0, 1), (-1, 1), 9),
            ("TOPPADDING", (0, 1), (-1, 1), 2),
            ("BOTTOMPADDING", (0, 0), (-1, 0), 2),
            ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ]))
        cells.append(inner)
    row = Table([cells], colWidths=[w] * n, hAlign="CENTER")
    row.setStyle(TableStyle([
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("LEFTPADDING", (0, 0), (-1, -1), 0),
        ("RIGHTPADDING", (0, 0), (-1, -1), 0),
    ]))
    story.append(Spacer(1, 10))
    story.append(KeepTogether([row]))
    story.append(Spacer(1, 12))


