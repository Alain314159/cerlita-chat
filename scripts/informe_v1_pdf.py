def make_chart():
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.font_manager as fm
    fm.fontManager.addfont(f"{FONT_DIR}/truetype/dejavu/DejaVuSans.ttf")
    import matplotlib.pyplot as plt
    plt.rcParams["font.sans-serif"] = ["DejaVu Sans"]
    plt.rcParams["axes.unicode_minus"] = False

    capas = [
        "Dispositivo real (instrumentados)",
        "UI Compose (Robolectric)",
        "Motor de chat (JVM)",
        "Protocolo y backend (e2e)",
        "Criptografía y claves (KAT)",
    ]
    vals = [0, 15, 60, 85, 95]
    fig, ax = plt.subplots(figsize=(7.6, 3.1), dpi=200, constrained_layout=True)
    bars = ax.barh(capas, vals, color="#8b7226", height=0.58, edgecolor="none")
    for b, v in zip(bars, vals):
        ax.text(v + 1.5, b.get_y() + b.get_height() / 2, f"{v}%",
                va="center", ha="left", fontsize=10, color="#1d1c1a")
    ax.set_xlim(0, 108)
    ax.spines["top"].set_visible(False)
    ax.spines["right"].set_visible(False)
    ax.spines["left"].set_visible(False)
    ax.spines["bottom"].set_color("#d1cab5")
    ax.tick_params(axis="y", length=0, labelsize=10.5, colors="#1d1c1a")
    ax.tick_params(axis="x", labelsize=9, colors="#838079")
    ax.set_xticks([0, 25, 50, 75, 100])
    ax.set_xticklabels(["0", "25", "50", "75", "100"])
    ax.grid(False)
    ax.set_xlabel("Profundidad de verificación (estimación fundamentada, %)", fontsize=9.5, color="#838079")
    fig.savefig(OUT_CHART, facecolor="white")
    plt.close(fig)


def chart_block(story, png, caption, max_h=250):
    from PIL import Image as PILImage
    im = PILImage.open(png)
    ow, oh = im.size
    ratio = min(AVAIL_W / ow, max_h / oh, 1.0)
    img = Image(png, width=ow * ratio, height=oh * ratio)
    story.append(Spacer(1, 16))
    story.append(KeepTogether([img, Spacer(1, 6), Paragraph(caption, S["caption"])]))
    story.append(Spacer(1, 14))


